package com.davils.kreate

import org.objectweb.asm.ClassVisitor
import org.objectweb.asm.FieldVisitor
import org.objectweb.asm.MethodVisitor
import org.objectweb.asm.Opcodes

internal class GradleReferenceCollector : ClassVisitor(Opcodes.ASM9) {
    val references: MutableSet<String> = linkedSetOf()

    override fun visit(
        version: Int,
        access: Int,
        name: String,
        signature: String?,
        superName: String?,
        interfaces: Array<out String>?
    ) {
        references.addAll(listOfNotNull(signature, superName))
        references.addAll(interfaces.orEmpty())
    }

    override fun visitField(
        access: Int,
        name: String,
        descriptor: String,
        signature: String?,
        value: Any?
    ): FieldVisitor? {
        references.addAll(listOfNotNull(descriptor, signature))
        return null
    }

    override fun visitMethod(
        access: Int,
        name: String,
        descriptor: String,
        signature: String?,
        exceptions: Array<out String>?
    ): MethodVisitor? {
        references.addAll(listOfNotNull(descriptor, signature))
        references.addAll(exceptions.orEmpty())
        return null
    }
}
